_FULL_TO_HALF = str.maketrans(
    "０１２３４５６７８９ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ"
    "ａｂｃｄｅｆｇｈｉｊｋｌｍｎｏｐｑｒｓｔｕｖｗｘｙｚ（）：；，．－／",
    "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz():;,.-/",
)

# 需要剔除的噪声片段
_NOISE_PATTERNS = [
    r"[(（]\s*(合并|母公司|附注\d*|注\d*)\s*[)）]",   # (合并)(注1) 等
    r"(损失|亏损|净亏损|减少|亏损总额)?以[-－—]号填列",  # "损失以-号填列"
    r"其中\s*[:：]",                                   # "其中:"
    r"[一二三四五六七八九十]+\s*[、.．]",              # "一、" 序号
    r"[(（]\s*[一二三四五六七八九十\d]+\s*[)）]",       # "(一)" "(1)" 序号
    r"加\s*[:：]|减\s*[:：]|其中\s*[:：]",
]


def normalize(name: str) -> str:
    """项目名归一化：全角转半角、去空白、去噪声、统一括号"""
    if not name:
        return ""
    s = str(name).translate(_FULL_TO_HALF)
    # 统一括号为半角
    s = s.replace("（", "(").replace("）", ")")
    # 去所有空白（含全角空格）
    s = re.sub(r"[\s\u3000]+", "", s)
    # 去噪声片段
    for pat in _NOISE_PATTERNS:
        s = re.sub(pat, "", s)
    # 去掉空括号与首尾标点
    s = re.sub(r"\(\s*\)", "", s)
    s = s.strip(":：、.．-—")
    return s


def has_cjk(text: str) -> bool:
    """判断文本是否含有中文字符"""
    return any("\u4e00" <= c <= "\u9fff" for c in text)


def canonical(name: str) -> str:
    """归一化 + 同义词映射，得到用于匹配的标准键。

    跨语言能力：若 name 为英文且能在词典中译为中文标准名，则先译为
    中文再走原归一化 + 同义词逻辑；未收录的英文则归一化为纯字母数字键，
    交由模糊匹配兜底（不会跨语言误配）。
    """
    if not name:
        return ""
    if not has_cjk(name):
        zh = translate_to_zh(name)
        if zh:
            name = zh
        else:
            return _norm_en(name)
    n = normalize(name)
    return SYNONYMS.get(n, n)
